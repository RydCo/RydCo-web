// Turns src/config/theme.mjs into everything that needs its colours: the CSS tokens, the favicon and the link-preview
// image. Runs before `next dev` and `next build`; run it yourself with `npm run theme`.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { activeTheme, shape, theme } from "../src/config/theme.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cssFile = join(root, "src/styles/theme.generated.css");
const iconFile = join(root, "src/app/icon.svg");
const ogFile = join(root, "public/og.png");

// ---------- Readability: the build stops if a theme fails these. ----------

const TEXT = 4.5; // WCAG AA for normal text
const GRAPHIC = 3; // WCAG AA for marks and icons
const pairs = [
  ["ink", "surface", TEXT],
  ["ink", "brand", TEXT],
  ["ink", "panel", TEXT],
  ["ink", "screen", TEXT],
  ["inkSoft", "surface", TEXT],
  ["inkSoft", "panel", TEXT],
  ["inkSoft", "screen", TEXT],
  ["surface", "ink", TEXT],
  ["surface", "inkSoft", TEXT],
  ["brand", "ink", TEXT],
  ["accent", "surface", TEXT],
  ["onAccent", "accent", TEXT],
  ["onTrust", "trust", TEXT],
  ["accent", "panel", GRAPHIC],
  ["accent", "screen", GRAPHIC],
];

function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const failures = pairs.filter(([fg, bg, min]) => contrast(theme[fg], theme[bg]) < min);
if (failures.length) {
  console.error(`Theme "${activeTheme}" isn't readable:`);
  for (const [fg, bg, min] of failures) console.error(`  ${fg} on ${bg} is ${contrast(theme[fg], theme[bg]).toFixed(2)}:1, needs ${min}:1`);
  process.exit(1);
}

// ---------- CSS tokens ----------

const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const stamp = createHash("sha256").update(JSON.stringify({ theme, shape })).digest("hex").slice(0, 12);
const stampLine = `/* Generated by scripts/build-theme.mjs from src/config/theme.mjs. Edit that file, not this one. Theme "${activeTheme}", ${stamp}. */`;
const previous = existsSync(cssFile) ? readFileSync(cssFile, "utf8") : "";
const css = `${stampLine}
@theme {
  --color-*: initial;
${Object.entries(theme)
  .map(([name, value]) => `  --color-${kebab(name)}: ${value};`)
  .join("\n")}
  --radius-surface: ${shape.surfaceRadius};
}
`;
writeFileSync(cssFile, css);

// ---------- Favicon ----------

const carShapes = `<rect x="-15" y="-10" width="30" height="8" rx="3"/>
    <path d="M-9 -10 L-5 -16 H6 L10 -10Z"/>
    <rect x="-4" y="-14.5" width="8" height="3.5" rx="1" fill="${theme.brand}"/>
    <circle cx="-8.5" cy="-1.5" r="3.2"/>
    <circle cx="8.5" cy="-1.5" r="3.2"/>`;
writeFileSync(
  iconFile,
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect width="64" height="64" rx="16" fill="${theme.brand}"/>
  <path d="M10 24 C10 40 14 46 22 46 L50 46" fill="none" stroke="${theme.ink}" stroke-width="6" stroke-linecap="round"/>
  <g transform="translate(40 46) scale(1.25)" fill="${theme.ink}">
    ${carShapes}
  </g>
</svg>
`,
);

// ---------- Link-preview image: only when the theme changed, since it's the one slow step. ----------

if (existsSync(ogFile) && previous.includes(stamp)) {
  console.log(`Theme "${activeTheme}" ready.`);
  process.exit(0);
}

const { ImageResponse } = await import("next/og.js");
const font = (file) => readFileSync(join(root, "scripts/assets/fonts", file));
const el = (type, style, ...children) => ({ type, props: { style, children: children.length === 1 ? children[0] : children } });
const svg = (props, ...children) => ({ type: "svg", props: { ...props, children } });
const shapeEl = (type, props) => ({ type, props });

const logo = el(
  "div",
  { position: "relative", display: "flex", width: 620, height: 248 },
  svg(
    { width: 620, height: 248, viewBox: "0 0 580 232", style: { position: "absolute", left: 0, top: 0 } },
    shapeEl("path", { d: "M8 118 C8 190 30 216 60 216 L520 216", fill: "none", stroke: theme.ink, strokeWidth: 13, strokeLinecap: "round", strokeLinejoin: "round" }),
    shapeEl("g", {
      transform: "translate(520 216) scale(2.6)",
      fill: theme.ink,
      children: [
        shapeEl("rect", { x: -15, y: -10, width: 30, height: 8, rx: 3 }),
        shapeEl("path", { d: "M-9 -10 L-5 -16 H6 L10 -10Z" }),
        shapeEl("rect", { x: -4, y: -14.5, width: 8, height: 3.5, rx: 1, fill: theme.brand }),
        shapeEl("circle", { cx: -8.5, cy: -1.5, r: 3.2 }),
        shapeEl("circle", { cx: 8.5, cy: -1.5, r: 3.2 }),
      ],
    }),
  ),
  el("div", { position: "absolute", left: 64, top: 24, fontSize: 160, fontWeight: 800, lineHeight: 1, letterSpacing: "-0.01em" }, "RydCo"),
);

const image = el(
  "div",
  { display: "flex", flexDirection: "column", justifyContent: "space-between", width: 1200, height: 630, padding: "76px 88px", background: theme.brand, color: theme.ink, fontFamily: "Urbanist" },
  logo,
  el(
    "div",
    { display: "flex", flexDirection: "column" },
    el("div", { fontSize: 64, fontWeight: 800, lineHeight: 1, letterSpacing: "-0.03em" }, "Your commute, in good company."),
    el("div", { marginTop: 18, fontSize: 28, fontWeight: 700, letterSpacing: "-0.01em" }, "Carpooling for daily commuters · Starting in Lahore"),
  ),
);

const png = new ImageResponse(image, {
  width: 1200,
  height: 630,
  fonts: [
    { name: "Urbanist", weight: 700, style: "normal", data: font("Urbanist-Bold.ttf") },
    { name: "Urbanist", weight: 800, style: "normal", data: font("Urbanist-ExtraBold.ttf") },
  ],
});
writeFileSync(ogFile, Buffer.from(await png.arrayBuffer()));
console.log(`Theme "${activeTheme}" ready, preview image redrawn.`);
